std::string Code_generator::emit_transition_tables() const {
    std::ostringstream oss;
    const std::size_t num_states = dfa_.size();

    oss << "// DFA Transition Table: [state][char] -> next_state (-1 for dead state)\n";
    oss << "static constexpr std::size_t dfa_state_count = " << num_states << ";\n";
    oss << "static constexpr int16_t dfa_transitions[" << num_states << "][256] = {\n";

    for (State_id s = 0; s < num_states; ++s) {
        oss << "    {";
        for (std::size_t c = 0; c < Char_set::alphabet_size; ++c) {
            State_id nxt = dfa_.transition(s, static_cast<unsigned char>(c));
            if (nxt == invalid_state) {
                oss << "-1";
            } else {
                oss << nxt;
            }
            if (c + 1 < Char_set::alphabet_size) {
                oss << ",";
            }
        }
        oss << "}";
        if (s + 1 < num_states) {
            oss << ",";
        }
        oss << "\n";
    }
    oss << "};\n\n";

    oss << "// DFA Accepting Rules: [state] -> rule_id (-1 for non-accepting)\n";
    oss << "static constexpr int16_t dfa_accepting_rules[" << num_states << "] = {";
    for (State_id s = 0; s < num_states; ++s) {
        Rule_id r = dfa_.state(s).rule_id;
        if (r == no_rule) {
            oss << "-1";
        } else {
            oss << r;
        }
        if (s + 1 < num_states) {
            oss << ", ";
        }
    }
    oss << "};\n\n";

    return oss.str();
}

std::string Code_generator::emit_actions() const {
    std::ostringstream oss;
    for (const auto& rule : spec_.rules) {
        oss << "            case " << rule.id << ":\n";
        oss << "                // Line " << rule.line_number << ": " << rule.pattern << "\n";
        std::string act = rule.action;
        // Trim leading/trailing whitespace
        while (!act.empty() && std::isspace(static_cast<unsigned char>(act.front()))) act.erase(0, 1);
        while (!act.empty() && std::isspace(static_cast<unsigned char>(act.back()))) act.pop_back();

        if (act.empty()) {
            oss << "                { /* ignore */ }\n";
        } else if (act.front() == '{' && act.back() == '}') {
            oss << "                " << act << "\n";
        } else {
            oss << "                {\n";
            oss << "                    " << act << "\n";
            oss << "                }\n";
        }
        oss << "                break;\n";
    }
    return oss.str();
}

std::string Code_generator::generate_header() const {
    std::ostringstream oss;
    oss << "#ifndef GENERATED_" << options_.class_name << "_HPP\n";
    oss << "#define GENERATED_" << options_.class_name << "_HPP\n\n";
    oss << "#include <iostream>\n";
    oss << "#include <string>\n";
    oss << "#include <string_view>\n";
    oss << "#include <cstddef>\n";
    oss << "#include <cstdint>\n\n";

    if (!options_.namespace_name.empty()) {
        oss << "namespace " << options_.namespace_name << " {\n\n";
    }

    oss << "class " << options_.class_name << " {\n";
    oss << "public:\n";
    oss << "    explicit " << options_.class_name << "(std::istream& in);\n";
    oss << "    explicit " << options_.class_name << "(std::string_view input);\n\n";
    oss << "    int yylex();\n\n";
    oss << "    [[nodiscard]] std::string_view text() const noexcept { return yytext; }\n";
    oss << "    [[nodiscard]] std::size_t length() const noexcept { return yyleng; }\n";
    oss << "    [[nodiscard]] int line() const noexcept { return yylineno; }\n";
    oss << "    [[nodiscard]] int column() const noexcept { return yycolumn; }\n\n";
    oss << "    std::string_view yytext{};\n";
    oss << "    std::size_t yyleng{0};\n";
    oss << "    int yylineno{1};\n";
    oss << "    int yycolumn{1};\n\n";
    oss << "private:\n";
    oss << "    void load_stream();\n";
    oss << "    [[nodiscard]] bool at_eof() const noexcept;\n";
    oss << "    [[nodiscard]] char peek_char() const noexcept;\n";
    oss << "    char consume_char() noexcept;\n";
    oss << "    void rollback_to(std::size_t pos, int line, int col) noexcept;\n\n";
    oss << "    std::string owned_buffer_{};\n";
    oss << "    std::string_view buffer_{};\n";
    oss << "    std::istream* in_{nullptr};\n";
    oss << "    std::size_t cursor_{0};\n";
    oss << "    int curr_line_{1};\n";
    oss << "    int curr_col_{1};\n";
    oss << "};\n\n";

    if (!options_.namespace_name.empty()) {
        oss << "} // namespace " << options_.namespace_name << "\n\n";
    }

    oss << "#endif // GENERATED_" << options_.class_name << "_HPP\n";
    return oss.str();
}

std::string Code_generator::generate_source() const {
    std::ostringstream oss;

    oss << "// Generated by lex_cpp - modern C++ Lexical Analyzer Generator\n";
    oss << "// Inspired by Bjarne Stroustrup's C++ principles: RAII, type safety, value semantics\n\n";

    // Section 1: User prologue
    if (!spec_.prologue.empty()) {
        oss << "// --- Begin User Prologue ---\n";
        oss << spec_.prologue << "\n";
        oss << "// --- End User Prologue ---\n\n";
    }

    oss << "#include <iostream>\n";
    oss << "#include <sstream>\n";
    oss << "#include <string>\n";
    oss << "#include <string_view>\n";
    oss << "#include <cstddef>\n";
    oss << "#include <cstdint>\n\n";

    if (!options_.namespace_name.empty()) {
        oss << "namespace " << options_.namespace_name << " {\n\n";
    }

    // Transition tables
    oss << emit_transition_tables();

    // Scanner class declaration & implementation
    oss << "class " << options_.class_name << " {\n";
    oss << "public:\n";
    oss << "    explicit " << options_.class_name << "(std::istream& in) : in_{&in} {\n";
    oss << "        load_stream();\n";
    oss << "    }\n\n";
    oss << "    explicit " << options_.class_name << "(std::string_view input) : buffer_{input}, in_{nullptr} {}\n\n";
    oss << "    int yylex() {\n";
    oss << "        while (true) {\n";
    oss << "            if (at_eof()) {\n";
    oss << "                return 0; // EOF token\n";
    oss << "            }\n\n";
    oss << "            std::size_t token_start = cursor_;\n";
    oss << "            int token_start_line = curr_line_;\n";
    oss << "            int token_start_col = curr_col_;\n\n";
    oss << "            int16_t current_state = 0;\n";
    oss << "            int16_t last_accepting_rule = -1;\n";
    oss << "            std::size_t last_accepting_pos = cursor_;\n";
    oss << "            int last_accepting_line = curr_line_;\n";
    oss << "            int last_accepting_col = curr_col_;\n\n";
    oss << "            if (dfa_accepting_rules[current_state] != -1) {\n";
    oss << "                last_accepting_rule = dfa_accepting_rules[current_state];\n";
    oss << "                last_accepting_pos = cursor_;\n";
    oss << "                last_accepting_line = curr_line_;\n";
    oss << "                last_accepting_col = curr_col_;\n";
    oss << "            }\n\n";
    oss << "            while (!at_eof()) {\n";
    oss << "                unsigned char c = static_cast<unsigned char>(peek_char());\n";
    oss << "                int16_t next_state = dfa_transitions[current_state][c];\n";
    oss << "                if (next_state == -1) {\n";
    oss << "                    break;\n";
    oss << "                }\n";
    oss << "                consume_char();\n";
    oss << "                current_state = next_state;\n";
    oss << "                if (dfa_accepting_rules[current_state] != -1) {\n";
    oss << "                    last_accepting_rule = dfa_accepting_rules[current_state];\n";
    oss << "                    last_accepting_pos = cursor_;\n";
    oss << "                    last_accepting_line = curr_line_;\n";
    oss << "                    last_accepting_col = curr_col_;\n";
    oss << "                }\n";
    oss << "            }\n\n";
    oss << "            if (last_accepting_rule != -1) {\n";
    oss << "                rollback_to(last_accepting_pos, last_accepting_line, last_accepting_col);\n";
    oss << "                yytext = buffer_.substr(token_start, last_accepting_pos - token_start);\n";
    oss << "                yyleng = yytext.size();\n";
    oss << "                yylineno = token_start_line;\n";
    oss << "                yycolumn = token_start_col;\n\n";
    oss << "                switch (last_accepting_rule) {\n";
    oss << emit_actions();
    oss << "                    default: break;\n";
    oss << "                }\n";
    oss << "            } else {\n";
    oss << "                // Default rule: echo unrecognized character\n";
    oss << "                rollback_to(token_start, token_start_line, token_start_col);\n";
    oss << "                char c = consume_char();\n";
    oss << "                yytext = buffer_.substr(token_start, 1);\n";
    oss << "                yyleng = 1;\n";
    oss << "                yylineno = token_start_line;\n";
    oss << "                yycolumn = token_start_col;\n";
    oss << "                std::cout.put(c);\n";
    oss << "            }\n";
    oss << "        }\n";
    oss << "    }\n\n";
    oss << "    [[nodiscard]] std::string_view text() const noexcept { return yytext; }\n";
    oss << "    [[nodiscard]] std::size_t length() const noexcept { return yyleng; }\n";
    oss << "    [[nodiscard]] int line() const noexcept { return yylineno; }\n";
    oss << "    [[nodiscard]] int column() const noexcept { return yycolumn; }\n\n";
    oss << "    std::string_view yytext{};\n";
    oss << "    std::size_t yyleng{0};\n";
    oss << "    int yylineno{1};\n";
    oss << "    int yycolumn{1};\n\n";
    oss << "private:\n";
    oss << "    void load_stream() {\n";
    oss << "        if (in_) {\n";
    oss << "            std::ostringstream ss;\n";
    oss << "            ss << in_->rdbuf();\n";
    oss << "            owned_buffer_ = ss.str();\n";
    oss << "            buffer_ = owned_buffer_;\n";
    oss << "        }\n";
    oss << "    }\n\n";
    oss << "    [[nodiscard]] bool at_eof() const noexcept {\n";
    oss << "        return cursor_ >= buffer_.size();\n";
    oss << "    }\n\n";
    oss << "    [[nodiscard]] char peek_char() const noexcept {\n";
    oss << "        return at_eof() ? '\\0' : buffer_[cursor_];\n";
    oss << "    }\n\n";
    oss << "    char consume_char() noexcept {\n";
    oss << "        if (at_eof()) return '\\0';\n";
    oss << "        char c = buffer_[cursor_++];\n";
    oss << "        if (c == '\\n') {\n";
    oss << "            ++curr_line_;\n";
    oss << "            curr_col_ = 1;\n";
    oss << "        } else {\n";
    oss << "            ++curr_col_;\n";
    oss << "        }\n";
    oss << "        return c;\n";
    oss << "    }\n\n";
    oss << "    void rollback_to(std::size_t pos, int line, int col) noexcept {\n";
    oss << "        cursor_ = pos;\n";
    oss << "        curr_line_ = line;\n";
    oss << "        curr_col_ = col;\n";
    oss << "    }\n\n";
    oss << "    std::string owned_buffer_{};\n";
    oss << "    std::string_view buffer_{};\n";
    oss << "    std::istream* in_{nullptr};\n";
    oss << "    std::size_t cursor_{0};\n";
    oss << "    int curr_line_{1};\n";
    oss << "    int curr_col_{1};\n";
    oss << "};\n\n";

    if (!options_.namespace_name.empty()) {
        oss << "} // namespace " << options_.namespace_name << "\n\n";
    }

    // Section 3: Epilogue or default main
    if (!spec_.epilogue.empty()) {
        oss << "// --- Begin User Epilogue ---\n";
        oss << spec_.epilogue << "\n";
        oss << "// --- End User Epilogue ---\n";
    } else if (options_.generate_main_if_missing) {
        oss << "#ifndef LEX_NO_MAIN\n";
        oss << "int main() {\n";
        if (!options_.namespace_name.empty()) {
            oss << "    " << options_.namespace_name << "::";
        }
        oss << options_.class_name << " lexer(std::cin);\n";
        oss << "    while (lexer.yylex() != 0) {}\n";
        oss << "    return 0;\n";
        oss << "}\n";
        oss << "#endif\n";
    }

    return oss.str();
}

